import { Block } from './blocks.js';

/**
 * Text the client (Claude Code, the desktop app, hooks, IDE plugins…) puts into a user message without the person
 * typing it. Matched against the start of a block that the tag splitter left as `human`.
 */
const INJECTED: Array<[RegExp, string]> = [
  [/^<total_tokens>/, 'budget'],
  [/^The user hasn't heard from you in a while/i, 'nudge'],
  [/^(Base directory for this skill:|\(Re-invocation of \/|Skill \/\S+ is already loaded)/, 'skill'],
  [/^# MCP Server Instructions/, 'mcp'],
  [/^The following (skills|deferred tools|agents|agent types|MCP servers|tools|plugins)\b[^\n]{0,80}\b(are|is|were|have)\b/i, 'context'],
  [/^(# Environment( update)?\s|You are powered by the model named |Today's date is \d)/, 'environment'],
  [/^The user's message contains \/\S+, which is the name of a skill/, 'skill'],
  [/^(## Exited Plan Mode|Plan mode is active|## Plan mode)/i, 'plan-mode'],
  [/^(SessionStart|SessionEnd|UserPromptSubmit|PreToolUse|PostToolUse|Stop|SubagentStop|PreCompact|Notification)(:\S+)? hook/, 'hook'],
  [/^(While auto mode is active|Auto mode is active)/i, 'auto-mode'],
  [/^Note: \S[^\n]{0,400} (changed on disk|was modified)/, 'file-changed'],
  [/^\[SYSTEM NOTIFICATION/, 'notification'],
  [/^(Another Claude session sent a message:|<cross-session-message)/, 'cross-session'],
  [/^<(side-sessions-event|ci-monitor-event|user-memory-input|system-notification|ide_opened_file|ide_selection|ide_diagnostics|new-diagnostics)\b/, 'event'],
  [/^Caveat: The messages below were generated by the user while running local commands/, 'caveat'],
  [/^(CRITICAL: Respond with TEXT ONLY|Your task is to create a detailed summary of the conversation so far)/, 'compact-request'],
  [/^(Called the \S+ tool with the following input|Result of calling the \S+ tool)/, 'tool-echo'],
  [/^Contents of \S[^\n]*CLAUDE\.md/, 'memory'],
  [/^(You are coming up with a succinct title|Stage 1 does NOT apply|Review the classification process|The following is the user's CLAUDE\.md configuration)/, 'helper'],
  [/^<\/?transcript>/, 'helper'],
];

const QUEUED_RE = /^The user sent the following message:/i;
const LOOP_RE = /\/loop\s+(?:\d+\s*[smhd]\w*\s+)?(\/[^\s`'"]+)/gi;

export function injectedTag(text: string): string | null {
  const t = text.trimStart();
  for (const [re, tag] of INJECTED) if (re.test(t)) return tag;
  return null;
}

export type ThreadRole = 'main' | 'subagent';

/**
 * Decides who really wrote each user-side block, looking at the whole user turn (the user blocks between two
 * assistant blocks):
 * - client-injected text becomes `system_reminder` (with a `tag`),
 * - text after tool results is injected, unless the person interrupted first,
 * - the expanded body of a prompt slash command / skill is not typed by the person,
 * - in a subagent thread the "user" is Claude itself (`agent_prompt`),
 * - a queued message ("The user sent the following message: …") is the person's,
 * - a prompt fired again and again by `/loop` is scheduled, not typed.
 *
 * Only `kind` and `meta` change: text and block boundaries stay, so stored content hashes remain valid.
 */
export function refineKinds(blocks: Block[], role: ThreadRole): Block[] {
  const out = blocks.slice();
  // prompts that `/loop <interval> <prompt>` re-sends on its own (also when only the compaction summary mentions it)
  const looped = new Set<string>();
  for (const b of blocks)
    if (b.kind === 'command' || b.meta?.tag === 'continuation-summary' || b.kind === 'system_reminder')
      for (const m of b.text.matchAll(LOOP_RE)) looped.add(m[1].trim());
  let i = 0;
  while (i < out.length) {
    if (out[i].role !== 'user') {
      i++;
      continue;
    }
    let j = i;
    while (j < out.length && out[j].role === 'user') j++;
    const turn = out.slice(i, j);
    const local = turn.some((b) => b.kind === 'local_output' || (b.kind === 'system_reminder' && /^(Caveat:|The command below was run)/.test(b.text)));
    let toolResult = false;
    let interrupted = false;
    let promptCommand = false;
    for (let k = i; k < j; k++) {
      const b = out[k];
      if (b.kind === 'tool_result') toolResult = true;
      else if (b.kind === 'interrupt') interrupted = true;
      else if (b.kind === 'command') {
        promptCommand = !local;
        if (looped.has(b.text.trim()) && !/^\/loop\b/.test(b.text)) out[k] = { ...b, kind: 'system_reminder', meta: { ...b.meta, tag: 'scheduled' } };
      }
      else if (b.kind === 'system_reminder' && QUEUED_RE.test(b.text.trimStart()) && role === 'main') out[k] = { ...b, kind: 'human', meta: { ...b.meta, queued: true } };
      else if (b.kind === 'human' || b.kind === 'agent_prompt') {
        const tag = injectedTag(b.text);
        if (tag) out[k] = { ...b, kind: 'system_reminder', meta: { ...b.meta, tag } };
        else if (role === 'subagent') out[k] = { ...b, kind: 'agent_prompt' };
        else if (toolResult && !interrupted) out[k] = { ...b, kind: 'system_reminder', meta: { ...b.meta, tag: 'injected' } };
        else if (promptCommand) out[k] = { ...b, kind: 'system_reminder', meta: { ...b.meta, tag: 'command-body' } };
        else if (b.kind === 'agent_prompt') out[k] = { ...b, kind: 'human' };
      }
    }
    i = j;
  }
  return out;
}

/** The first user turn: every block before the first assistant block. Never changes once a thread exists. */
export function firstTurn(blocks: Block[]): Block[] {
  const k = blocks.findIndex((b) => b.role === 'assistant');
  return k < 0 ? blocks : blocks.slice(0, k);
}

/**
 * Blocks that identify a turn. Client-injected reminders (date, budget, environment…) are re-rendered by the
 * client and may differ between two requests of the same chat; the compaction summary is the exception.
 */
export const stable = (b: Block) => b.kind !== 'system_reminder' || b.meta?.tag === 'continuation-summary';

export function identityOf(turn: Block[]): Block[] {
  const s = turn.filter(stable);
  return s.length ? s : turn;
}

/** Text a person (or, in a subagent, Claude) wrote first: used for titles. */
export function firstPrompt(blocks: Block[]): Block | undefined {
  return blocks.find((b) => b.kind === 'human' || b.kind === 'command' || b.kind === 'agent_prompt');
}
